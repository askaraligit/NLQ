_BUSINESS_RULES = (
    "All monetary amounts are INR and use exact decimal values.",
    (
        "Sales order and sales invoice values are customer-facing; purchase values are "
        "supplier-facing."
    ),
    "Order totals equal subtotal plus tax_amount; item line totals are generated by PostgreSQL.",
    "Stock availability is quantity minus reserved_quantity.",
    "The database applies tenant row-level security; do not filter or infer tenant identifiers.",
)


class SchemaService:
    """Build a small, approved schema context instead of disclosing every relation."""

    def __init__(self, max_tables: int) -> None:
        self.max_tables = max_tables
        self._catalog = self._build_catalog()
        self._relationships = self._build_relationships()

    @staticmethod
    def _build_catalog() -> dict[str, SchemaTable]:
        catalog: dict[str, SchemaTable] = {}
        for table in registered_models.Base.metadata.tables.values():
            if table.schema != "erp" or table.name not in _TABLE_DETAILS:
                continue
            description, keywords = _TABLE_DETAILS[table.name]
            catalog[table.name] = SchemaTable(
                name=table.name,
                description=description,
                columns=tuple(
                    SchemaColumn(
                        name=column.name,
                        data_type=str(column.type),
                        nullable=column.nullable,
                    )
                    for column in table.columns
                    if column.name != "tenant_id"
                ),
                keywords=keywords,
            )
        return catalog

    @staticmethod
    def _build_relationships() -> tuple[SchemaRelationship, ...]:
        relationships: list[SchemaRelationship] = []
        for table in registered_models.Base.metadata.tables.values():
            if table.schema != "erp":
                continue
            for constraint in table.foreign_key_constraints:
                for element in constraint.elements:
                    target = element.column.table
                    if target.schema == "erp":
                        relationships.append(
                            SchemaRelationship(
                                source_table=table.name,
                                source_column=element.parent.name,
                                target_table=target.name,
                                target_column=element.column.name,
                            )
                        )
        return tuple(relationships)

    def context_for(self, question: str) -> SchemaContext:
        tokens = set(re.findall(r"[a-z0-9]+", question.lower()))
        ranked: list[tuple[int, str]] = []
        for table in self._catalog.values():
            search_terms = set(table.name.split("_")) | set(table.keywords)
            score = len(tokens & search_terms)
            ranked.append((score, table.name))
        ranked.sort(key=lambda item: (-item[0], item[1]))
        selected = [name for score, name in ranked if score > 0][: self.max_tables]
        if not selected:
            selected = ["sales_orders", "sales_order_items", "products", "customers"]

        # Include direct joins for the selected business relations when capacity permits.
        for relationship in self._relationships:
            if relationship.source_table in selected and relationship.target_table not in selected:
                selected.append(relationship.target_table)
            elif (
                relationship.target_table in selected and relationship.source_table not in selected
            ):
                selected.append(relationship.source_table)
            if len(selected) >= self.max_tables:
                break
        selected = selected[: self.max_tables]
        selected_set = set(selected)
        return SchemaContext(
            tables=tuple(self._catalog[name] for name in selected),
            relationships=tuple(
                relationship
                for relationship in self._relationships
                if relationship.source_table in selected_set
                and relationship.target_table in selected_set
            ),
            business_rules=_BUSINESS_RULES,
        )
