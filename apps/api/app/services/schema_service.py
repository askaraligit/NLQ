"""Curated ERP schema context and question-based relation selection."""

from __future__ import annotations

import re
from dataclasses import dataclass

from app import models as registered_models


@dataclass(frozen=True)
class SchemaColumn:
    name: str
    data_type: str
    nullable: bool


@dataclass(frozen=True)
class SchemaTable:
    name: str
    description: str
    columns: tuple[SchemaColumn, ...]
    keywords: tuple[str, ...]


@dataclass(frozen=True)
class SchemaRelationship:
    source_table: str
    source_column: str
    target_table: str
    target_column: str


@dataclass(frozen=True)
class SchemaContext:
    tables: tuple[SchemaTable, ...]
    relationships: tuple[SchemaRelationship, ...]
    business_rules: tuple[str, ...]

    @property
    def table_names(self) -> frozenset[str]:
        return frozenset(table.name for table in self.tables)

    def column_names(self, table_name: str) -> frozenset[str]:
        for table in self.tables:
            if table.name == table_name:
                return frozenset(column.name for column in table.columns)
        return frozenset()

    def as_prompt_data(self) -> dict[str, object]:
        return {
            "schema": "erp",
            "tables": [
                {
                    "name": table.name,
                    "description": table.description,
                    "columns": [
                        {
                            "name": column.name,
                            "type": column.data_type,
                            "nullable": column.nullable,
                        }
                        for column in table.columns
                    ],
                }
                for table in self.tables
            ],
            "relationships": [relationship.__dict__ for relationship in self.relationships],
            "business_rules": list(self.business_rules),
        }


